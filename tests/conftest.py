"""Shared pytest configuration for XDX Studio.

Phase 01.6C portability fix (DEF-P016B-017): the reference MP4s are Git LFS objects. A clone made with
``GIT_LFS_SKIP_SMUDGE=1`` (or an audit bundle that excludes them) only has pointer files or nothing.
Tests that genuinely need the real bytes carry ``@pytest.mark.requires_lfs`` and are skipped - not
failed - in that environment. Everything else must pass without the MP4s.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

ROOT_DIR = Path(__file__).resolve().parent.parent
DB_ROOT = ROOT_DIR / "reference_database"
_LFS_PREFIX = b"version https://git-lfs.github.com/spec/v1"
# Test profiles: "core" (default, no LFS needed) | "full_integration" (real MP4s mandatory).
FULL_INTEGRATION = os.environ.get("XDX_TEST_PROFILE", "core").strip().lower() == "full_integration"


def reference_media_hydrated() -> bool:
    """True only if every registered reference MP4 exists as real bytes of the registered size."""
    reg = json.loads((DB_ROOT / "reference_registry.json").read_text(encoding="utf-8"))
    for entry in reg["references"]:
        p = DB_ROOT / entry["path"]
        if not p.is_file() or p.stat().st_size != int(entry["bytes"]):
            return False
        with p.open("rb") as fh:
            if fh.read(len(_LFS_PREFIX)).startswith(_LFS_PREFIX):
                return False
    return True


def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    if reference_media_hydrated():
        return
    if FULL_INTEGRATION:
        return  # Full Integration: never skip; pytest_runtest_setup turns missing media into a failure
    skip = pytest.mark.skip(
        reason="requires_lfs: reference MP4s not hydrated (run `git lfs pull` to enable this test)"
    )
    for item in items:
        if "requires_lfs" in item.keywords:
            item.add_marker(skip)


# ----------------------------------------------------------------------------- Phase 01.6D


@pytest.fixture
def trusted_approver(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """Register a throw-away Ed25519 approver in a tmp trust registry (private key stays in the test).

    Simulates the human's offline device. The real repository registry is never touched.
    """
    from datetime import timedelta

    import governance.trusted_approval as ta

    priv, pub = ta.generate_approver_keypair()
    reg = tmp_path / "trusted_approvers_test.json"
    reg.write_text(
        json.dumps(
            {
                "schema_version": "4.0.0-phase01.6d",
                "registry_id": "xdx_trusted_human_approvers",
                "policy": "test-only registry generated by tests/conftest.py",
                "approvers": [
                    {
                        "key_id": "test-human-1",
                        "algorithm": "ed25519",
                        "public_key_b64url": pub,
                        "owner": "pytest",
                        "added_at": "2026-11-28T00:00:00+00:00",
                        "revoked": False,
                    }
                ],
            }
        ),
        encoding="utf-8",
    )
    monkeypatch.setattr(ta, "DEFAULT_TRUST_REGISTRY_PATH", reg)

    class _Approver:
        registry_path = reg
        key_id = "test-human-1"
        private_key = priv

        def sign(self, *, package_dir: Path, project_id: str, package_version: str = "v1",
                 scopes=("all_production",), ttl=timedelta(hours=1), now=None, nonce=None,
                 manifest_digest: str | None = None, key=None) -> str:
            from intelligence.state_and_approval import compute_package_digest

            digest = manifest_digest or compute_package_digest(package_dir)[0]
            return ta.sign_approval_token(
                private_key_raw=key or priv, key_id=self.key_id, project_id=project_id,
                package_version=package_version, manifest_digest=digest, scopes=list(scopes),
                ttl=ttl, now=now, nonce=nonce,
            )

    return _Approver()


def pytest_runtest_setup(item: pytest.Item) -> None:
    if FULL_INTEGRATION and "requires_lfs" in item.keywords and not reference_media_hydrated():
        pytest.fail(
            "XDX_TEST_PROFILE=full_integration but reference MP4s are missing or unhydrated LFS pointers "
            "(run `git lfs pull`). Media absence is a failure in this profile, not a skip.",
            pytrace=False,
        )
